/** The palette for CORE_SPRITES, with the trim in the faction's colour. */
export function corePalette(factionColor: string): Palette {
  return { ...CORE_COLORS, f: factionColor, F: darker(factionColor) };
}

/** The colour at 55% brightness: "#rgb" and "#rrggbb" directly, anything else by the browser. */
function darker(color: string): string {
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(color)?.[1];
  if (!hex) return `color-mix(in srgb, ${color} 55%, black)`;
  const full = hex.length === 3 ? [...hex].map((c) => c + c).join("") : hex;
  const channel = (i: number) =>
    Math.round(parseInt(full.slice(i, i + 2), 16) * 0.55)
      .toString(16)
      .padStart(2, "0");
  return `#${channel(0)}${channel(2)}${channel(4)}`;
}

